-- KNOWLEDGE: normalized knowledge-graph tables + Cortex Search service (auto-embedded).

create or replace schema PM_MEDIATOR.KNOWLEDGE;

create or replace TABLE PM_MEDIATOR.KNOWLEDGE.ARTIFACT_CONCEPT (
	ARTIFACT_ID VARCHAR(16777216),
	CONCEPT_ID VARCHAR(16777216),
	RELEVANCE FLOAT
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.ARTIFACT_LABEL (
	ARTIFACT_ID VARCHAR(16777216),
	LABEL_ID VARCHAR(16777216)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.CODE_FILE (
	ARTIFACT_ID VARCHAR(16777216) NOT NULL,
	REPO VARCHAR(16777216),
	PATH VARCHAR(16777216),
	LANGUAGE VARCHAR(16777216),
	LOC NUMBER(38,0),
	BRANCH VARCHAR(16777216),
	primary key (ARTIFACT_ID)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.CONCEPT (
	CONCEPT_ID VARCHAR(16777216) NOT NULL,
	NAME VARCHAR(16777216),
	DESCRIPTION VARCHAR(16777216),
	primary key (CONCEPT_ID)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.DB_COLUMN (
	COLUMN_ID VARCHAR(16777216) NOT NULL,
	DB_TABLE_ARTIFACT_ID VARCHAR(16777216),
	COLUMN_NAME VARCHAR(16777216),
	DATA_TYPE VARCHAR(16777216),
	IS_NULLABLE VARCHAR(16777216),
	ORDINAL NUMBER(38,0),
	COMMENT VARCHAR(16777216),
	primary key (COLUMN_ID)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.DB_TABLE (
	ARTIFACT_ID VARCHAR(16777216) NOT NULL,
	DATABASE_NAME VARCHAR(16777216),
	SCHEMA_NAME VARCHAR(16777216),
	TABLE_NAME VARCHAR(16777216),
	ROW_COUNT NUMBER(38,0),
	TABLE_KIND VARCHAR(16777216),
	primary key (ARTIFACT_ID)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.DOC_PAGE (
	ARTIFACT_ID VARCHAR(16777216) NOT NULL,
	DOC_SOURCE VARCHAR(16777216),
	SECTION_PATH VARCHAR(16777216),
	URL VARCHAR(16777216),
	VERSION VARCHAR(16777216),
	primary key (ARTIFACT_ID)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.INGESTION_RUN (
	RUN_ID VARCHAR(16777216) NOT NULL,
	SOURCE_SYSTEM_ID VARCHAR(16777216),
	STARTED_AT TIMESTAMP_TZ(9),
	ROWS_INGESTED NUMBER(38,0),
	STATUS VARCHAR(16777216),
	primary key (RUN_ID)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.ISSUE (
	ARTIFACT_ID VARCHAR(16777216) NOT NULL,
	ISSUE_KEY VARCHAR(16777216),
	PROJECT_KEY VARCHAR(16777216),
	ISSUE_TYPE VARCHAR(16777216),
	PRIORITY VARCHAR(16777216),
	STATUS VARCHAR(16777216),
	LABELS VARCHAR(16777216),
	URL VARCHAR(16777216),
	CREATED_AT TIMESTAMP_TZ(9),
	PARENT_ARTIFACT_ID VARCHAR(16777216),
	primary key (ARTIFACT_ID)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.KNOWLEDGE_ARTIFACT (
	ARTIFACT_ID VARCHAR(16777216) NOT NULL,
	SOURCE_SYSTEM_ID VARCHAR(16777216),
	ARTIFACT_TYPE VARCHAR(16777216),
	EXTERNAL_ID VARCHAR(16777216),
	URL VARCHAR(16777216),
	TITLE VARCHAR(16777216),
	STATUS VARCHAR(16777216),
	CREATED_AT TIMESTAMP_TZ(9),
	UPDATED_AT TIMESTAMP_TZ(9),
	CONTENT_HASH VARCHAR(16777216),
	INGESTED_AT TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP(),
	primary key (ARTIFACT_ID)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.KNOWLEDGE_CHUNK (
	CHUNK_ID VARCHAR(16777216) NOT NULL,
	ARTIFACT_ID VARCHAR(16777216),
	CHUNK_INDEX NUMBER(38,0),
	CONTENT VARCHAR(16777216),
	LINE_START NUMBER(38,0),
	LINE_END NUMBER(38,0),
	primary key (CHUNK_ID)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.KNOWLEDGE_LINK (
	LINK_ID VARCHAR(16777216) NOT NULL,
	FROM_ARTIFACT_ID VARCHAR(16777216),
	TO_ARTIFACT_ID VARCHAR(16777216),
	RELATION_TYPE VARCHAR(16777216),
	CONFIDENCE FLOAT,
	ORIGIN VARCHAR(16777216),
	primary key (LINK_ID)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.LABEL (
	LABEL_ID VARCHAR(16777216) NOT NULL,
	SOURCE_SYSTEM_ID VARCHAR(16777216),
	NAME VARCHAR(16777216),
	primary key (LABEL_ID)
);
create or replace TABLE PM_MEDIATOR.KNOWLEDGE.SOURCE_SYSTEM (
	SOURCE_SYSTEM_ID VARCHAR(16777216) NOT NULL,
	DISPLAY_NAME VARCHAR(16777216),
	KIND VARCHAR(16777216),
	BASE_URL VARCHAR(16777216),
	primary key (SOURCE_SYSTEM_ID)
);
create or replace task PM_MEDIATOR.KNOWLEDGE.REFRESH_GIT
	warehouse=PM_MEDIATOR_WH
	schedule='USING CRON 0 6 * * 1 UTC'
	COMMENT='Weekly fetch of the dtc-starter Git repository to keep code knowledge fresh'
	as ALTER GIT REPOSITORY PM_MEDIATOR.MOCK.DTC_STARTER_REPO FETCH;
create or replace cortex search service PM_MEDIATOR.KNOWLEDGE.KNOWLEDGE_SEARCH
	ON CONTENT
	attributes ARTIFACT_ID,SOURCE_SYSTEM_ID,ARTIFACT_TYPE,TITLE,URL,LINE_START,LINE_END
	warehouse='PM_MEDIATOR_WH'
	target_lag='1 hour'
	refresh_mode=INCREMENTAL
	as SELECT ch.CONTENT, ch.CHUNK_ID, ch.ARTIFACT_ID,
         a.SOURCE_SYSTEM_ID, a.ARTIFACT_TYPE, a.TITLE, a.URL,
         ch.LINE_START, ch.LINE_END
  FROM PM_MEDIATOR.KNOWLEDGE.KNOWLEDGE_CHUNK ch
  JOIN PM_MEDIATOR.KNOWLEDGE.KNOWLEDGE_ARTIFACT a ON a.ARTIFACT_ID = ch.ARTIFACT_ID;